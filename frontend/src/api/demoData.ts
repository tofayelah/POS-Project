// Helper to load full operational demo data
export async function uploadFullOperationalDemoData(): Promise<{
  success: boolean;
  message: string;
  stats: {
    company: string;
    businessUnits: number;
    branches: number;
    warehouses: number;
    storageLocations: number;
    categories: number;
    brands: number;
    units: number;
    products: number;
    suppliers: number;
    customers: number;
    purchases: number;
    purchaseOrders: number;
    supplierReturns: number;
    posTerminals: number;
    posSessions: number;
    sales: number;
    stockMovements: number;
  };
}> {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      localStorage.setItem(STORAGE_KEYS.COMPANY, JSON.stringify(DEMO_COMPANY));
      localStorage.setItem(STORAGE_KEYS.ACTIVE_COMPANY_ID, '1');
      localStorage.setItem(STORAGE_KEYS.BUSINESS_UNITS, JSON.stringify(DEMO_BUSINESS_UNITS));
      localStorage.setItem(STORAGE_KEYS.BRANCHES, JSON.stringify(DEMO_BRANCHES));
      localStorage.setItem(STORAGE_KEYS.BRANCHES_ALT, JSON.stringify(DEMO_BRANCHES));
      localStorage.setItem(STORAGE_KEYS.ACTIVE_BRANCH_ID, '1');
      localStorage.setItem(STORAGE_KEYS.WAREHOUSES, JSON.stringify(DEMO_WAREHOUSES));
      localStorage.setItem(STORAGE_KEYS.WAREHOUSES_ALT, JSON.stringify(DEMO_WAREHOUSES));
      localStorage.setItem(STORAGE_KEYS.STORAGE_LOCATIONS, JSON.stringify(DEMO_STORAGE_LOCATIONS));
      localStorage.setItem(STORAGE_KEYS.STORAGE_LOCATIONS_ALT, JSON.stringify(DEMO_STORAGE_LOCATIONS));
      localStorage.setItem(STORAGE_KEYS.CATEGORIES, JSON.stringify(DEMO_CATEGORIES));
      localStorage.setItem(STORAGE_KEYS.BRANDS, JSON.stringify(DEMO_BRANDS));
      localStorage.setItem(STORAGE_KEYS.UNITS, JSON.stringify(DEMO_UNITS));

      const normalizedProducts = DEMO_PRODUCTS.map((p) => {
        let barcode = p.barcode || p.variants?.[0]?.barcodes?.[0]?.barcode || '';
        if (barcode && barcode.startsWith('880')) {
          const supShort = p.supplier_short_name || p.supplier?.short_name || 'SUP';
          barcode = `${supShort}-${barcode.replace(/^880/, '').padStart(8, '0').slice(-8)}`;
        }
        const cost = Number(p.cost_price ?? p.variants?.[0]?.cost_price ?? 0);
        const retail = Number(p.retail_price ?? p.price ?? p.variants?.[0]?.selling_price ?? 0);
        const mrp = Number(p.mrp ?? p.variants?.[0]?.mrp ?? retail);
        const stock = Number(p.stock_quantity ?? p.variants?.[0]?.available_quantity ?? 0);
        const variants = (p.variants && p.variants.length > 0)
          ? p.variants.map((v: any) => {
              let vBarcode = v.barcodes?.[0]?.barcode || v.barcode || barcode;
              if (vBarcode && vBarcode.startsWith('880')) {
                const supShort = p.supplier_short_name || p.supplier?.short_name || 'SUP';
                vBarcode = `${supShort}-${vBarcode.replace(/^880/, '').padStart(8, '0').slice(-8)}`;
              }
              return {
                ...v,
                barcode: vBarcode,
                barcodes: v.barcodes && v.barcodes.length > 0
                  ? v.barcodes.map((b: any) => ({
                      ...b,
                      barcode: String(b.barcode || '').startsWith('880')
                        ? `${p.supplier_short_name || p.supplier?.short_name || 'SUP'}-${String(b.barcode).replace(/^880/, '').padStart(8, '0').slice(-8)}`
                        : b.barcode,
                    }))
                  : vBarcode
                    ? [{ id: v.id || 1, barcode: vBarcode, is_primary: true }]
                    : [],
              };
            })
          : [
              {
                id: p.id,
                product_id: p.id,
                sku: p.sku || p.product_code,
                variant_name: p.name,
                cost_price: cost,
                selling_price: retail,
                mrp: mrp,
                available_quantity: stock,
                status: 'ACTIVE',
                barcode,
                barcodes: barcode ? [{ id: p.id, barcode, barcode_type: 'CODE-128', is_primary: true }] : [],
              },
            ];

        return {
          ...p,
          barcode,
          cost_price: cost,
          retail_price: retail,
          price: retail,
          mrp,
          stock_quantity: stock,
          variants,
        };
      });

      localStorage.setItem(STORAGE_KEYS.PRODUCTS, JSON.stringify(normalizedProducts));
      localStorage.setItem(STORAGE_KEYS.SUPPLIERS, JSON.stringify(DEMO_SUPPLIERS));
      localStorage.setItem(STORAGE_KEYS.CUSTOMERS, JSON.stringify(DEMO_CUSTOMERS));
      localStorage.setItem(STORAGE_KEYS.PURCHASES, JSON.stringify(DEMO_PURCHASES));
      localStorage.setItem(STORAGE_KEYS.PURCHASE_ORDERS, JSON.stringify(DEMO_PURCHASE_ORDERS));
      localStorage.setItem(STORAGE_KEYS.SUPPLIER_RETURNS, JSON.stringify(DEMO_SUPPLIER_RETURNS));
      localStorage.setItem(STORAGE_KEYS.POS_TERMINALS, JSON.stringify(DEMO_POS_TERMINALS));
      localStorage.setItem(STORAGE_KEYS.POS_SESSIONS, JSON.stringify(DEMO_POS_SESSIONS));
      localStorage.setItem(STORAGE_KEYS.SALES, JSON.stringify(DEMO_SALES));
      localStorage.setItem(STORAGE_KEYS.STOCK_MOVEMENTS, JSON.stringify(DEMO_STOCK_MOVEMENTS));
      localStorage.setItem(STORAGE_KEYS.DEMO_SEEDED, 'true');

      // Dispatch global events to refresh all UI contexts
      window.dispatchEvent(new CustomEvent('retailcore_tenant_changed', { detail: DEMO_COMPANY }));
      window.dispatchEvent(new CustomEvent('retailcore_branch_changed', { detail: { branchId: 1 } }));
      window.dispatchEvent(new CustomEvent('retailcore_products_updated', { detail: normalizedProducts }));
      window.dispatchEvent(new CustomEvent('retailcore_suppliers_updated', { detail: DEMO_SUPPLIERS }));
      window.dispatchEvent(new CustomEvent('retailcore_demo_seeded', { detail: { timestamp: new Date().toISOString() } }));
    }

    // Attempt backend sync if backend API is reachable
    try {
      await api.post('/settings/maintenance/demo', { size: 'medium' });
    } catch (apiErr) {
      // Backend may be in preview or offline; client data is already seeded
    }

    return {
      success: true,
      message: 'Full operational demo data uploaded and initialized successfully.',
      stats: {
        company: DEMO_COMPANY.name,
        businessUnits: DEMO_BUSINESS_UNITS.length,
        branches: DEMO_BRANCHES.length,
        warehouses: DEMO_WAREHOUSES.length,
        storageLocations: DEMO_STORAGE_LOCATIONS.length,
        categories: DEMO_CATEGORIES.length,
        brands: DEMO_BRANDS.length,
        units: DEMO_UNITS.length,
        products: DEMO_PRODUCTS.length,
        suppliers: DEMO_SUPPLIERS.length,
        customers: DEMO_CUSTOMERS.length,
        purchases: DEMO_PURCHASES.length,
        purchaseOrders: DEMO_PURCHASE_ORDERS.length,
        supplierReturns: DEMO_SUPPLIER_RETURNS.length,
        posTerminals: DEMO_POS_TERMINALS.length,
        posSessions: DEMO_POS_SESSIONS.length,
        sales: DEMO_SALES.length,
        stockMovements: DEMO_STOCK_MOVEMENTS.length,
      },
    };
  } catch (error: any) {
    return {
      success: false,
      message: error?.message || 'Failed to upload demo data.',
      stats: {
        company: 'Error',
        businessUnits: 0,
        branches: 0,
        warehouses: 0,
        storageLocations: 0,
        categories: 0,
        brands: 0,
        units: 0,
        products: 0,
        suppliers: 0,
        customers: 0,
        purchases: 0,
        purchaseOrders: 0,
        supplierReturns: 0,
        posTerminals: 0,
        posSessions: 0,
        sales: 0,
        stockMovements: 0,
      },
    };
  }
}

/**
 * Automatically ensures demo data exists in browser local storage on startup.
 */
export function ensureDemoDataSeeded(): boolean {
  if (typeof window === 'undefined' || !window.localStorage) return false;
  try {
    const isSeeded = localStorage.getItem(STORAGE_KEYS.DEMO_SEEDED) === 'true';
    const hasCompany = !!localStorage.getItem(STORAGE_KEYS.COMPANY);
    const hasBranches = !!localStorage.getItem(STORAGE_KEYS.BRANCHES_ALT) || !!localStorage.getItem(STORAGE_KEYS.BRANCHES);
    
    if (!isSeeded || !hasCompany || !hasBranches) {
      uploadFullOperationalDemoData();
      return true;
    }
  } catch (e) {
    // Local storage access fallback
  }
  return false;
}

